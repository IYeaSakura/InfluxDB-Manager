_TRANSLATIONS = {
    "zh_CN": _zh_CN,
    "en_US": _en_US,
}

_current_language = "zh_CN"


def set_language(language: str) -> None:
    global _current_language
    if language in _TRANSLATIONS:
        _current_language = language


def get_language() -> str:
    return _current_language


def tr(key: str, **kwargs) -> str:
    """Translate ``key`` into the current language, falling back to English,
    then to the key itself. ``kwargs`` are used for ``str.format``."""
    table = _TRANSLATIONS.get(_current_language, {})
    text = table.get(key)
    if text is None:
        text = _en_US.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
